// Release signing credentials live OUTSIDE the repository. Point ADVAULT_KEYSTORE_PROPERTIES at a
// properties file (storeFile, storePassword, keyAlias, keyPassword) or use ~/.advault/keystore.properties.
val keystoreProps = Properties().apply {
    val path = System.getenv("ADVAULT_KEYSTORE_PROPERTIES")
        ?: "${System.getProperty("user.home")}/.advault/keystore.properties"
    val f = file(path)
    if (f.exists()) f.inputStream().use { load(it) }
}

